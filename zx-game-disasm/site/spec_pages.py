#!/usr/bin/env python3
"""Turn the behavior pages (spec/*.md) into a SkoolKit ref file.

    spec_pages.py OUT.ref SKOOL SPEC.md...

Each Markdown file becomes one page, [Page:Spec-<name>], at spec/<name>.html,
with the Markdown rendered to HTML as its PageContent. A #TABLE span is kept
as SkoolKit table markup, its cells rendered from Markdown. A link to another
spec/*.md file becomes a link to that page. Inline code that names a label of
the main listing (read from SKOOL's @label directives) becomes a #R link to it.
The pages are listed on the home page, as the group Spec, under the title of
spec/index.md ("Behavior specification" when it has none): the index first,
then the pages in the order spec/index.md links them, then any others by name.
The Markdown stays the single source.

The framework runs it from site.mk, which passes the ref it writes to
skool2html after the project's own refs. The home page draws the group only
where the project's [Index] names Spec, as assets/game.ref.template does: a
plain [Index] in a project ref replaces SkoolKit's default list, and an
[Index+] here would replace it too where the project has none. It needs the
`markdown` package.
"""

import html
import os
import re
import sys

import markdown

INDEX_ID = 'Spec'
INDEX_HEADER = 'Behavior specification'


def read_labels(skool):
    """Map each label of the skool file to the address it labels."""
    labels = {}
    pending = None
    with open(skool, encoding='utf-8') as f:
        for line in f:
            m = re.match(r'@label=(\w+)', line)
            if m:
                pending = m.group(1)
                continue
            m = re.match(r'[a-z*! ]?\$([0-9A-F]{4})\b', line)
            if m and pending:
                labels[pending] = m.group(1)
                pending = None
    return labels


def page_id(name):
    return 'Spec-{}'.format(name)


TABLE_RE = re.compile(r'#TABLE(\([^)]*\))?(.*?)TABLE#', re.S)
ROW_RE = re.compile(r'\{(.*?)\}', re.S)


def inline(text, labels):
    """HTML for one piece of Markdown, ready for SkoolKit's macro expansion."""
    body = markdown.markdown(text, extensions=['tables', 'toc'], output_format='html')
    # Keep '#' from starting a skool macro before the labels add their own.
    body = re.sub(r'#(?=[A-Z(])', '&#35;', body)
    # A link to another spec page, with or without an anchor.
    body = re.sub(r'href="([\w-]+)\.md(#[\w-]+)?"',
                  lambda m: 'href="{}.html{}"'.format(m.group(1), m.group(2) or ''), body)

    def link_label(m):
        name = m.group(1)
        if name in labels:
            return '<code>#R${}({})</code>'.format(labels[name], name)
        return m.group(0)
    return re.sub(r'<code>(\w+)</code>', link_label, body)


def table(m, labels):
    """A #TABLE span, its cells rendered from Markdown, on one line."""
    rows = []
    for row in ROW_RE.findall(m.group(2)):
        cells = []
        for cell in row.split('|'):
            cell = cell.strip()
            markup = re.match(r'=\w+(?:,\w+)*\s+', cell)
            prefix = markup.group(0) if markup else ''
            html_cell = inline(cell[len(prefix):], labels)
            cells.append(prefix + re.sub(r'^<p>(.*)</p>$', r'\1', html_cell, flags=re.S))
        rows.append('{ ' + ' | '.join(cells) + ' }')
    return '#TABLE{} {} TABLE#'.format(m.group(1) or '', ' '.join(rows))


def convert(text, labels):
    # The tables are SkoolKit's own, as on every other page of the site.
    tables = []

    def hold(m):
        tables.append(table(m, labels))
        return '\n\nSPECTABLE{}\n\n'.format(len(tables) - 1)
    body = inline(TABLE_RE.sub(hold, text), labels)
    body = re.sub(r'<p>SPECTABLE(\d+)</p>', lambda m: tables[int(m.group(1))], body)

    title = ''
    m = re.search(r'<h1[^>]*>(.*?)</h1>', body, re.S)
    if m:
        title = html.unescape(re.sub(r'<[^>]+>', '', m.group(1))).strip()
        body = body[:m.start()] + body[m.end():]

    # A ref file value is one line. A code block's line breaks are its
    # content, so inside <pre> each one is written as a character reference.
    body = re.sub(r'<pre>.*?</pre>', lambda m: m.group(0).replace('\n', '&#10;'),
                  body, flags=re.S)
    return title, ' '.join(body.split('\n'))


def main(out, skool, mdfiles):
    labels = read_labels(skool)
    pages = {}
    for path in mdfiles:
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding='utf-8') as f:
            text = f.read()
        pages[name] = (text,) + convert(text, labels)

    order = []
    if 'index' in pages:
        order.append('index')
        for name in re.findall(r'\]\(([\w-]+)\.md', pages['index'][0]):
            if name in pages and name not in order:
                order.append(name)
    order += sorted(n for n in pages if n not in order)

    lines = ['; Generated by site/spec_pages.py from spec/*.md. Do not edit.', '']
    header = pages['index'][1] if 'index' in pages else ''
    lines += ['[Index:{}:{}]'.format(INDEX_ID, header or INDEX_HEADER)]
    lines += [page_id(n) for n in order]
    lines += ['', '[Paths+]']
    lines += ['{}=spec/{}.html'.format(page_id(n), n) for n in order]
    for section in ('Titles', 'Links'):
        lines += ['', '[{}+]'.format(section)]
        lines += ['{}={}'.format(page_id(n), pages[n][1] or n) for n in order]
    for n in order:
        lines += ['', '[Page:{}]'.format(page_id(n)), 'PageContent=' + pages[n][2]]
    with open(out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3:])
